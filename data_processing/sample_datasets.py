"""Sample and normalise datasets based on a sampling configuration.

This script reads gzipped JSONL datasets, samples records according to a CSV
configuration (as generated by :mod:`create_sampling_config`), converts the
records to a unified triplet-style format and writes gzipped JSONL shards.
"""

from __future__ import annotations

import argparse
import csv
import gzip
import json
import random
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from tqdm import tqdm

JsonDict = dict[str, Any]


@dataclass
class SamplingEntry:
    """Configuration for sampling a single input file."""

    file: str
    sample_ratio: float
    total_lines: int | None = None
    sampled_lines: int | None = None
    dataset_share: float | None = None

    def should_sample(self, rng: random.Random) -> bool:
        return rng.random() <= self.sample_ratio

    def estimated_samples(self) -> float | None:
        """Return the expected number of samples for this entry."""

        if self.sampled_lines is not None:
            return float(self.sampled_lines)
        if self.total_lines is not None:
            return float(self.total_lines) * self.sample_ratio
        return None


@dataclass
class NormalisedRecord:
    """Representation of a sample in the normalised output format."""

    query: str
    pos: list[str]
    neg: list[str]
    source: str

    def to_json(self) -> str:
        payload: JsonDict = {
            "query": self.query,
            "pos": self.pos,
            "neg": self.neg,
            "source": self.source,
        }
        return json.dumps(payload, ensure_ascii=False)


def parse_sampling_config(path: Path) -> list[SamplingEntry]:
    entries: list[SamplingEntry] = []
    all_sampled_lines = 0
    with path.open("r", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            file = row["file"].strip()
            ratio_str = row["sample_ratio"].strip()
            ratio = float(ratio_str)
            total_lines = int(float(row["total_lines"]))
            sampled_lines = int(total_lines * ratio)
            all_sampled_lines += sampled_lines
            dataset_share = None
            entries.append(
                SamplingEntry(
                    file=file,
                    sample_ratio=max(0.0, min(1.0, ratio)),
                    total_lines=total_lines,
                    sampled_lines=sampled_lines,
                    dataset_share=dataset_share,
                )
            )
    # update dataset shares
    for entry in entries:
        entry.dataset_share = entry.sampled_lines / all_sampled_lines
    if not entries:
        raise ValueError("Sampling config is empty")
    return entries


def extract_all_texts(record: Any) -> list[str]:
    """Return all text snippets contained in the raw record."""

    texts: list[str] = []
    if isinstance(record, list):
        texts.extend(str(item) for item in record if isinstance(item, str))
    elif isinstance(record, dict):
        for key in ("query", "pos", "neg", "set"):
            value = record.get(key)
            if isinstance(value, str):
                texts.append(value)
            elif isinstance(value, list):
                texts.extend(str(item) for item in value if isinstance(item, str))
    elif isinstance(record, str):
        texts.append(record)
    return texts


def collect_negative_corpus(
    path: Path,
    pool_size: int,
    rng: random.Random,
) -> list[str]:
    """Collect a reservoir of candidate texts for negative sampling."""

    if not path.is_file():
        raise FileNotFoundError(f"Input file not found: {path}")

    pool: list[str] = []
    seen = 0
    with gzip.open(path, mode="rt", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                data = json.loads(line)
            except json.JSONDecodeError:
                continue
            texts = extract_all_texts(data)
            for text in texts:
                seen += 1
                if len(pool) < pool_size:
                    pool.append(text)
                else:
                    idx = rng.randint(0, seen - 1)
                    if idx < pool_size:
                        pool[idx] = text
            if seen >= pool_size * 10:
                break
    return pool


def normalise_record(raw: Any, source: str) -> NormalisedRecord | None:
    """Convert a raw dataset record to the unified output format."""

    query: str | None = None
    pos_list: list[str] = []
    neg_list: list[str] = []

    if isinstance(raw, list):
        if len(raw) == 2:
            query, pos = map(str, raw)
            pos_list = [pos]
        elif len(raw) == 3:
            query, pos, neg = map(str, raw)
            pos_list = [pos]
            neg_list = [neg]
        else:
            return None
    elif isinstance(raw, dict):
        if "query" in raw:
            query = str(raw["query"])
            pos = raw.get("pos")
            if isinstance(pos, list):
                pos_list = [str(x) for x in pos]
            elif isinstance(pos, str):
                pos_list = [pos]
            # optional negatives
            neg = raw.get("neg")
            if isinstance(neg, list):
                neg_list = [str(x) for x in neg]
            elif isinstance(neg, str):
                neg_list = [neg]
        elif "set" in raw:
            items = [str(x) for x in raw.get("set", []) if isinstance(x, str)]
            if len(items) >= 2:
                query, *rest = items
                pos_list = rest
        else:
            return None
    else:
        return None

    if not query or not pos_list:
        return None

    return NormalisedRecord(
        query=query,
        pos=pos_list,
        neg=neg_list,
        source=source,
    )


def sample_negatives(
    record: NormalisedRecord,
    pool: list[str],
    rng: random.Random,
    desired: int,
) -> None:
    """Ensure the record contains at least ``desired`` negative examples."""

    if len(record.neg_list) >= desired:
        record.neg_list = record.neg_list[:desired]
        return

    needed = desired - len(record.neg_list)
    neg_candidates = rng.sample(pool, needed * 2)
    exclude = {record.query, *record.pos_list}
    available = [text for text in neg_candidates if text not in exclude]
    record.neg_list.extend(available[:needed])


def iter_normalised_records(
    path: Path,
    entry: SamplingEntry,
    rng: random.Random,
    limit: int | None = None,
) -> Iterable[NormalisedRecord]:
    if limit is not None and limit <= 0:
        return

    yielded = 0
    with gzip.open(path, mode="rt", encoding="utf-8") as fh:
        for line in fh:
            if limit is not None and yielded >= limit:
                break
            if not entry.should_sample(rng):
                continue
            line = line.strip()
            if not line:
                continue
            try:
                data = json.loads(line)
            except json.JSONDecodeError:
                continue
            record = normalise_record(data, source=entry.file)
            if record is not None:
                yielded += 1
                yield record


def write_sharded_output(
    records: Iterable[NormalisedRecord],
    output_dir: Path,
    max_samples: int | None,
    shard_size: int,
) -> int:
    output_dir.mkdir(parents=True, exist_ok=True)
    shard_index = 0
    written = 0
    shard_file: gzip.GzipFile | None = None

    def open_new_shard() -> gzip.GzipFile:
        nonlocal shard_index
        shard_path = output_dir / f"shard_{shard_index:05d}.jsonl.gz"
        shard_index += 1
        return gzip.open(shard_path, mode="wt", encoding="utf-8")

    try:
        for record in records:
            if max_samples is not None and written >= max_samples:
                break
            if shard_file is None or written % shard_size == 0:
                if shard_file is not None:
                    shard_file.close()
                shard_file = open_new_shard()
            assert shard_file is not None
            shard_file.write(record.to_json() + "\n")
            written += 1
    finally:
        if shard_file is not None:
            shard_file.close()
    return written


def compute_sampling_plan(
    entries: list[SamplingEntry], max_samples: int | None
) -> tuple[list[int | None], int | None]:
    """Determine how many records to sample from each dataset."""

    estimated: list[float | None] = []
    for entry in entries:
        estimate = entry.estimated_samples()
        if estimate is None and max_samples is not None and entry.dataset_share is not None:
            estimate = max_samples * max(0.0, min(1.0, entry.dataset_share))
        estimated.append(estimate)
    known_indices = [idx for idx, value in enumerate(estimated) if value is not None]
    plan: list[int | None] = [None] * len(entries)

    if not known_indices:
        return plan, None

    totals = [max(0.0, estimated[idx]) for idx in known_indices]
    total_estimated = sum(totals)

    if total_estimated == 0:
        for idx in known_indices:
            plan[idx] = 0
        return plan, 0

    if max_samples is None or total_estimated <= max_samples:
        for idx in known_indices:
            plan[idx] = int(round(estimated[idx]))
        total_planned = sum(plan[idx] for idx in known_indices)
        return plan, total_planned

    scale = max_samples / total_estimated
    scaled_values = [estimated[idx] * scale for idx in known_indices]
    floors = [int(value) for value in scaled_values]
    remainder = max_samples - sum(floors)

    if remainder > 0:
        fractions = [value - floor for value, floor in zip(scaled_values, floors)]
        order = sorted(range(len(known_indices)), key=lambda i: fractions[i], reverse=True)
        for offset in order[:remainder]:
            floors[offset] += 1

    for value, idx in zip(floors, known_indices):
        plan[idx] = value

    return plan, max_samples


def save_sampling_plan(
    plan_rows: Iterable[tuple[SamplingEntry, int | None, float | None]],
    output_dir: Path,
    filename: str = "sampling_plan.txt",
) -> Path:
    """Persist the sampling plan sorted by share in descending order."""

    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / filename

    rows = list(plan_rows)
    rows.sort(
        key=lambda item: item[2] if item[2] is not None else float("-inf"),
        reverse=True,
    )

    with output_path.open("w", encoding="utf-8") as fh:
        fh.write("Sampling plan:\n")
        for entry, target, share in rows:
            share_text = f"{share:.2%}" if share is not None else "N/A"
            fh.write(f"{entry.file}\ttarget={target}\tshare={share_text}\n")

    return output_path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Sample datasets to unified format")
    parser.add_argument("input_dir", type=Path, help="Directory containing input jsonl.gz files")
    parser.add_argument("sampling_config", type=Path, help="CSV sampling configuration")
    parser.add_argument("output_dir", type=Path, help="Directory where output shards are stored")
    parser.add_argument(
        "--max-samples",
        type=int,
        default=None,
        help="Maximum number of records to write",
    )
    parser.add_argument(
        "--max-samples-per-shard",
        type=int,
        default=512_000,
        help="Maximum number of records per output shard",
    )
    parser.add_argument(
        "--negative-samples",
        type=int,
        default=0,
        help="Number of negatives to ensure per record",
    )
    parser.add_argument(
        "--negative-pool-size",
        type=int,
        default=1_000_000,
        help="Number of candidate negatives retained in memory",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=22,
        help="Random seed for sampling",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    rng = random.Random(args.seed)

    entries = parse_sampling_config(args.sampling_config)

    input_dir: Path = args.input_dir
    output_dir: Path = args.output_dir

    if not input_dir.is_dir():
        raise NotADirectoryError(f"Input directory does not exist: {input_dir}")

    sampling_plan, planned_total = compute_sampling_plan(entries, args.max_samples)
    total_for_share = (
        planned_total
        if planned_total is not None and planned_total > 0
        else sum(value for value in sampling_plan if value is not None)
    )

    plan_rows: list[tuple[SamplingEntry, int | None, float | None]] = []

    for entry, target in zip(entries, sampling_plan):
        share = target / total_for_share
        plan_rows.append((entry, target, share))

    save_sampling_plan(plan_rows, output_dir)

    negative_rng = random.Random(args.seed + 1)

    records: list[NormalisedRecord] = []

    for entry, target in tqdm(zip(entries, sampling_plan), desc="Processing records", total=len(entries)):
        path = input_dir / entry.file
        if target is not None and target <= 0:
            continue
        if args.negative_samples > 0:
            negative_pool = collect_negative_corpus(
                path=path,
                pool_size=args.negative_pool_size,
                rng=negative_rng,
            )
        limit = target if target is not None else None
        for record in iter_normalised_records(path, entry, rng, limit=limit):
            if args.negative_samples > 0:
                sample_negatives(record, negative_pool, rng, desired=args.negative_samples)
            records.append(record)

    shuffle_rng = random.Random(args.seed + 2)
    shuffle_rng.shuffle(records)

    total_written = write_sharded_output(
        records=records,
        output_dir=output_dir,
        max_samples=args.max_samples,
        shard_size=max(1, args.max_samples_per_shard),
    )

    if total_written == 0:
        raise RuntimeError("No samples were written. Check your sampling configuration.")


if __name__ == "__main__":
    main()
